//! Golden vectors (golden/vectors.json): the formats two components must agree on, computed here and
//! checked again by each other component's own tests (near-antibody's commitment, the vending
//! contract's Borsh layout), so neither side can drift alone. `GOLDEN_WRITE=1` rewrites the file.

use std::path::PathBuf;

use alloy_primitives::{Address, B256};
use antibody_cli::{cmd, practice};
use antibody_verifier::{bundle::sender_address, manifest::deployer, run::reserved_address};
use serde_json::{json, Value};

fn path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../golden/vectors.json")
}

fn vectors() -> Value {
    let salt = B256::repeat_byte(0x07);
    let blob = [0x11u8; 32];
    let commitment = |key: &str, round: u32, hunter: &str| {
        json!({"program_key": key, "round": round, "hunter": hunter, "blob_sha256": hex::encode(blob),
               "commitment": hex::encode(cmd::commitment(key, round, hunter, &blob))})
    };
    let anchor = B256::repeat_byte(0xab);
    let vend_key = [0x09u8; 32];
    let senders: Vec<Value> = (0u8..2).map(|i| json!({"salt": format!("{salt:#x}"), "index": i, "address": format!("{:#x}", sender_address(&salt, i))})).collect();
    json!({
        "_note": "Generated by crates/cli/tests/golden.rs (GOLDEN_WRITE=1); checked there and by contracts/near-antibody and contracts/practice-vending tests",
        "commitment": [commitment("bounty.antibody.testnet/0", 0, "agent-a.antibody.testnet"), commitment("bounty.test.near/1", 2, "ann.practice.test.near")],
        "sender_address": senders,
        "reserved_address": {"program_key": "bounty.antibody.testnet/0", "anchor_hash": format!("{anchor:#x}"), "address": format!("{:#x}", reserved_address("bounty.antibody.testnet/0", anchor))},
        "deployer": {"address": format!("{:#x}", deployer()), "create_0": format!("{:#x}", deployer().create(0)), "create_1": format!("{:#x}", deployer().create(1))},
        "public_vend_key": practice::public_vend_signer("practice.antibody.testnet").public_key_str(),
        "vend_args": {"name": "ann", "public_key": hex::encode(vend_key), "borsh": hex::encode(practice::vend_args("ann", &vend_key))},
    })
}

#[test]
fn golden_vectors_hold() {
    let now = vectors();
    if std::env::var("GOLDEN_WRITE").is_ok() {
        std::fs::create_dir_all(path().parent().unwrap()).unwrap();
        std::fs::write(path(), serde_json::to_string_pretty(&now).unwrap() + "\n").unwrap();
        return;
    }
    let committed: Value = serde_json::from_str(&std::fs::read_to_string(path()).expect("golden/vectors.json (GOLDEN_WRITE=1 writes it)")).unwrap();
    assert_eq!(now, committed, "a format changed: if on purpose, rewrite with GOLDEN_WRITE=1 and update every checker");
    let a: Address = committed["deployer"]["address"].as_str().unwrap().parse().unwrap();
    assert_eq!(a, deployer());
}
