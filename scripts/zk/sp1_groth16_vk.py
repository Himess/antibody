"""Writes SP1's Groth16 verifying keys in the encoding NEAR's alt_bn128 host functions take, for
contracts/near-t2 (docs/zk.md).

NEAR reads field elements little-endian, and a G2 point as (x.c0, x.c1, y.c0, y.c1); SP1, gnark and
the EVM write them big-endian, and G2 as (x.c1, x.c0, y.c1, y.c0). The keys come from SP1's published
Solidity verifiers (sp1-contracts, contracts/src/<version>/: Groth16Verifier.sol for the points,
SP1VerifierGroth16.sol for the selector and the vk root). For the version the zk guest pins (SP1 6.10.0,
whose Groth16 circuit is v6.1.0's), every point is also checked against the gnark-compressed key SP1
ships (crates/verifier/vk-artifacts/groth16_vk.bin) and the selector against its sha256.

usage: sp1_groth16_vk.py <sp1-contracts dir with v6.0.0/ and v6.1.0/> <SP1 6.10.0 groth16_vk.bin> <out.rs>
"""
import hashlib, re, sys

P = 0x30644E72E131A029B85045B68181585D97816A916871CA8D3C208C16D87CFD47


def solidity_constants(path):
    out = {}
    for m in re.finditer(r"uint256\s+constant\s+(\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*;", open(path).read()):
        out[m.group(1)] = int(m.group(2), 0)
    return out


def returned(path, fn):
    t = open(path).read()
    m = re.search(fn + r"\(\)[^{]*\{\s*return\s+(0x[0-9a-fA-F]{64})", t)
    return bytes.fromhex(m.group(1)[2:])


def le(n):
    return n.to_bytes(32, "little")


def neg(y):
    return (P - y) % P


def compress_g1(x, y):
    b = bytearray(x.to_bytes(32, "big"))
    b[0] |= 0xC0 if y > neg(y) else 0x80
    return bytes(b)


def compress_g2(x0, x1, y0, y1):
    b = bytearray(x1.to_bytes(32, "big") + x0.to_bytes(32, "big"))
    b[0] |= 0xC0 if (y1, y0) > (neg(y1), neg(y0)) else 0x80
    return bytes(b)


def key(dir_, version):
    c = solidity_constants(f"{dir_}/{version}/Groth16Verifier.sol")
    sp1 = f"{dir_}/{version}/SP1VerifierGroth16.sol"
    k = {
        "selector": returned(sp1, "VERIFIER_HASH")[:4],
        "verifier_hash": returned(sp1, "VERIFIER_HASH"),
        "vk_root": returned(sp1, "VK_ROOT"),
        "alpha": (c["ALPHA_X"], c["ALPHA_Y"]),
        "ic": [(c["CONSTANT_X"], c["CONSTANT_Y"])] + [(c[f"PUB_{i}_X"], c[f"PUB_{i}_Y"]) for i in range(5)],
    }
    for n in ("BETA", "GAMMA", "DELTA"):
        k[n.lower() + "_neg"] = (c[f"{n}_NEG_X_0"], c[f"{n}_NEG_X_1"], c[f"{n}_NEG_Y_0"], c[f"{n}_NEG_Y_1"])
    return k


def check_against_gnark(k, vk_bin):
    """SP1's gnark key holds alpha, beta, gamma, delta and K compressed; the Solidity key negates beta,
    gamma and delta. Every point must match, and the selector is the key file's sha256 prefix."""
    assert hashlib.sha256(vk_bin).digest() == k["verifier_hash"], "VERIFIER_HASH is sha256(groth16_vk.bin)"
    assert vk_bin[0:32] == compress_g1(*k["alpha"]), "alpha"
    for name, off in (("beta_neg", 64), ("gamma_neg", 128), ("delta_neg", 224)):
        x0, x1, y0, y1 = k[name]
        assert vk_bin[off:off + 64] == compress_g2(x0, x1, neg(y0), neg(y1)), name
    n = int.from_bytes(vk_bin[288:292], "big")
    assert n == len(k["ic"]) == 6, "five public inputs"
    for i, (x, y) in enumerate(k["ic"]):
        assert vk_bin[292 + 32 * i:324 + 32 * i] == compress_g1(x, y), f"K[{i}]"


def arr(b):
    return "[" + ", ".join(f"0x{x:02x}" for x in b) + "]"


def rust_key(name, k, doc):
    g1 = lambda p: le(p[0]) + le(p[1])
    g2 = lambda p: le(p[0]) + le(p[1]) + le(p[2]) + le(p[3])
    lines = [f"/// {doc}", f"pub const {name}: Sp1Groth16Vk = Sp1Groth16Vk {{",
             f"    selector: {arr(k['selector'])},",
             f"    vk_root: {arr(k['vk_root'])},",
             f"    alpha: {arr(g1(k['alpha']))},",
             f"    beta_neg: {arr(g2(k['beta_neg']))},",
             f"    gamma_neg: {arr(g2(k['gamma_neg']))},",
             f"    delta_neg: {arr(g2(k['delta_neg']))},",
             "    ic: ["] + [f"        {arr(g1(p))}," for p in k["ic"]] + ["    ],", "};", ""]
    return "\n".join(lines)


def main():
    contracts, vk_path, out = sys.argv[1], sys.argv[2], sys.argv[3]
    v60, v61 = key(contracts, "v6.0.0"), key(contracts, "v6.1.0")
    check_against_gnark(v61, open(vk_path, "rb").read())
    head = ('//! Generated by scripts/zk/sp1_groth16_vk.py: SP1\'s Groth16 verifying keys in the encoding NEAR\'s\n'
            '//! alt_bn128 host functions take (little-endian field elements; G2 as (x.c0, x.c1, y.c0, y.c1)).\n'
            '//! Source: sp1-contracts, contracts/src/v6.0.0 and v6.1.0 (Groth16Verifier.sol, SP1VerifierGroth16.sol);\n'
            f'//! v6.1.0\'s points equal SP1 6.10.0\'s crates/verifier/vk-artifacts/groth16_vk.bin (sha256 {v61["verifier_hash"].hex()}).\n'
            '//! Do not edit by hand.\n\nuse crate::Sp1Groth16Vk;\n\n')
    body = rust_key("SP1_V6_0_0", v60, "SP1 v6.0.0's Groth16 circuit: SP1's published fixture proof (sp1-project-template) uses it.")
    body += "\n" + rust_key("SP1_V6_10_0", v61, "SP1 6.10.0's Groth16 circuit (v6.1.0's), the version crates/zk/guest pins.")
    open(out, "w", newline="\n").write(head + body)
    print(f"wrote {out}: v6.0.0 selector {v60['selector'].hex()}, v6.10.0 selector {v61['selector'].hex()} (checked against groth16_vk.bin)")


main()
